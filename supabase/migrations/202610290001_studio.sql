begin;
create schema if not exists studio_private;
revoke all on schema studio_private from public;

create table public.halls (
 id bigint generated by default as identity primary key,
 name text not null, code text not null unique, style text not null,
 capacity integer not null, "hourlyRate" integer not null,
 description text not null default '', "deletedAt" timestamptz
);
create table public.photographers (
 id bigint generated by default as identity primary key,
 "firstName" text not null, "lastName" text not null,
 specialization text not null, bio text not null default '',
 "experienceYears" integer not null default 0, "hourlyRate" integer not null,
 "deletedAt" timestamptz
);
create table public.clients (
 id bigint generated by default as identity primary key,
 "fullName" text not null, email text not null unique,
 phone text not null default '', "clientType" text not null default 'Частный',
 company text not null default '', notes text not null default '',
 "deletedAt" timestamptz
);
create table public.subscriptions (
 id bigint generated by default as identity primary key,
 "clientId" bigint not null unique references public.clients(id),
 number text not null unique, "issuedAt" date not null,
 "expiresAt" date not null, "discountPercent" integer not null default 0,
 "deletedAt" timestamptz
);
create table public.equipment (
 id bigint generated by default as identity primary key,
 name text not null, category text not null, manufacturer text not null default '',
 "hallId" bigint not null references public.halls(id), quantity integer not null,
 "pricePerDay" integer not null default 0, "deletedAt" timestamptz
);
create table public.services (
 id bigint generated by default as identity primary key,
 name text not null unique, category text not null, price integer not null,
 description text not null default '', "deletedAt" timestamptz
);
create table public.bookings (
 id bigint generated by default as identity primary key,
 "clientId" bigint not null references public.clients(id),
 "hallId" bigint not null references public.halls(id), email text not null,
 "accessCode" text not null unique default ('FF-' || upper(substr(md5(random()::text),1,12))),
 date date not null, "startTime" time not null default '10:00',
 "durationHours" integer not null, participants integer not null,
 "shootingType" text not null, comment text not null default '',
 status text not null default 'active', "totalPrice" numeric(12,2) not null default 0,
 "costBreakdown" jsonb not null default '{}', "deletedAt" timestamptz
);
create table public.payments (
 id bigint generated by default as identity primary key,
 "bookingId" bigint not null references public.bookings(id),
 amount numeric(12,2) not null, method text not null, status text not null default 'paid',
 "paidAt" date not null default current_date, note text not null default '',
 "deletedAt" timestamptz
);
create table public.photographer_halls (
 "photographerId" bigint references public.photographers(id) on delete cascade,
 "hallId" bigint references public.halls(id), primary key ("photographerId","hallId")
);
create table public.booking_photographers (
 "bookingId" bigint references public.bookings(id) on delete cascade,
 "photographerId" bigint references public.photographers(id),
 primary key ("bookingId","photographerId")
);
create table public.booking_services (
 "bookingId" bigint references public.bookings(id) on delete cascade,
 "serviceId" bigint references public.services(id), primary key ("bookingId","serviceId")
);
create table public.profiles (
 id bigint generated by default as identity primary key,
 auth_id uuid not null unique references auth.users(id) on delete cascade,
 username text not null unique, "fullName" text not null, email text not null,
 role text not null default 'client' check (role in ('client','manager','admin')),
 "clientId" bigint unique references public.clients(id)
);
create index bookings_schedule on public.bookings("hallId",date,"startTime") where "deletedAt" is null and status='active';
create index booking_photographers_person on public.booking_photographers("photographerId");
create index payments_booking on public.payments("bookingId");

create function studio_private.fail(field text, message text) returns void
language plpgsql set search_path=pg_catalog as $$
begin
 raise sqlstate 'PT422' using message=message, detail=jsonb_build_object(field,message)::text;
end $$;

create function studio_private.current_profile() returns public.profiles
language sql stable security definer set search_path=pg_catalog,public as $$
 select p from public.profiles p where auth_id=auth.uid()
$$;

create function studio_private.on_signup() returns trigger
language plpgsql security definer set search_path=pg_catalog,public,studio_private as $$
declare client_id bigint; full_name text; login_name text;
begin
 full_name:=trim(coalesce(new.raw_user_meta_data->>'fullName',''));
 login_name:=lower(trim(coalesce(new.raw_user_meta_data->>'username','')));
 if length(full_name) not between 2 and 100 then perform studio_private.fail('fullName','ФИО от 2 до 100 символов'); end if;
 if login_name !~ '^[a-z0-9_]{3,40}$' then perform studio_private.fail('username','Логин: 3–40 латинских букв, цифр или подчёркиваний'); end if;
 insert into public.clients("fullName",email) values(full_name,new.email) returning id into client_id;
 -- Role from user metadata is intentionally ignored.
 insert into public.profiles(auth_id,username,"fullName",email,"clientId")
 values(new.id,login_name,full_name,new.email,client_id);
 return new;
end $$;
create trigger focusframe_signup after insert on auth.users for each row execute function studio_private.on_signup();

-- Validate every writable field before casting and storing it.
create function studio_private.validate(entity text, data jsonb) returns void
language plpgsql set search_path=pg_catalog,public,studio_private as $$
declare spec jsonb; rule jsonb; field text; value text; n numeric; min_n numeric; max_n numeric;
begin
 spec:=case entity
 when 'halls' then '{"name":["s",2,100],"code":["s",2,30],"style":["s",2,60],"capacity":["i",1,500],"hourlyRate":["i",0,1000000],"description":["s",0,1000]}'::jsonb
 when 'photographers' then '{"firstName":["s",2,60],"lastName":["s",2,60],"specialization":["s",2,80],"bio":["s",0,1000],"experienceYears":["i",0,80],"hourlyRate":["i",0,1000000]}'::jsonb
 when 'clients' then '{"fullName":["s",2,100],"email":["e",3,254],"phone":["s",0,25],"clientType":["s",2,30],"company":["s",0,100],"notes":["s",0,1000]}'::jsonb
 when 'equipment' then '{"name":["s",2,100],"category":["s",2,60],"manufacturer":["s",0,100],"hallId":["i",1,999999999],"quantity":["i",1,10000],"pricePerDay":["i",0,1000000]}'::jsonb
 when 'subscriptions' then '{"clientId":["i",1,999999999],"number":["s",3,40],"issuedAt":["d",0,0],"expiresAt":["d",0,0],"discountPercent":["i",0,50]}'::jsonb
 when 'services' then '{"name":["s",2,100],"category":["s",2,60],"price":["i",0,1000000],"description":["s",0,1000]}'::jsonb
 when 'bookings' then '{"clientId":["i",1,999999999],"hallId":["i",1,999999999],"email":["e",3,254],"date":["d",0,0],"durationHours":["i",1,24],"participants":["i",1,500],"shootingType":["s",3,40],"comment":["s",0,300],"accessCode":["s",6,40]}'::jsonb
 when 'payments' then '{"bookingId":["i",1,999999999],"amount":["n",0.01,999999999],"method":["s",2,30],"status":["s",2,30],"paidAt":["d",0,0],"note":["s",0,300]}'::jsonb
 else '{}'::jsonb end;
 for field,rule in select * from jsonb_each(spec) loop
  value:=data->>field; min_n:=(rule->>1)::numeric; max_n:=(rule->>2)::numeric;
  if rule->>0 in ('s','e') then
   if value is null or length(trim(value)) not between min_n and max_n then
    perform studio_private.fail(field,format('Длина поля от %s до %s символов',min_n,max_n)); end if;
   if rule->>0='e' and value !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then perform studio_private.fail(field,'Укажите корректную почту'); end if;
  elsif rule->>0 in ('i','n') then
   if value is null or value !~ '^[0-9]+(\.[0-9]+)?$' then perform studio_private.fail(field,'Укажите число'); end if;
   n:=value::numeric;
   if n not between min_n and max_n or (rule->>0='i' and trunc(n)<>n) then perform studio_private.fail(field,format('Допустимое значение от %s до %s',min_n,max_n)); end if;
  elsif rule->>0='d' then
   begin
    if value is null or value !~ '^\d{4}-\d{2}-\d{2}$' then raise invalid_datetime_format; end if;
    perform value::date;
   exception when datetime_field_overflow or invalid_datetime_format then perform studio_private.fail(field,'Укажите дату ГГГГ-ММ-ДД'); end;
  end if;
 end loop;
 if entity='clients' then
  if data->>'phone'<>'' and data->>'phone' !~ '^\+?[0-9 ()-]{7,25}$' then perform studio_private.fail('phone','Некорректный телефон'); end if;
  if data->>'clientType' not in ('Частный','Корпоративный') then perform studio_private.fail('clientType','Выберите тип клиента'); end if;
 end if;
 if entity='subscriptions' and (data->>'expiresAt')::date<(data->>'issuedAt')::date then perform studio_private.fail('expiresAt','Окончание раньше начала'); end if;
 if entity='payments' then
  if data->>'method' not in ('Карта','Наличные','Перевод') then perform studio_private.fail('method','Выберите способ оплаты'); end if;
  if data->>'status' not in ('paid','pending','refunded') then perform studio_private.fail('status','Недопустимый статус оплаты'); end if;
 end if;
 if entity='bookings' then
  if coalesce(data->>'status','') not in ('active','cancelled','completed') then perform studio_private.fail('status','Недопустимый статус'); end if;
  if coalesce(data->>'startTime','') !~ '^([01][0-9]|2[0-3]):[0-5][0-9](:00)?$' then perform studio_private.fail('startTime','Время ЧЧ:ММ'); end if;
  if (data->>'startTime')::time + make_interval(hours=>(data->>'durationHours')::int) > time '23:59:59'
   or extract(epoch from (data->>'startTime')::time)/3600+(data->>'durationHours')::int>24 then perform studio_private.fail('durationHours','Съёмка должна закончиться до полуночи'); end if;
 end if;
end $$;

create function studio_private.row_json(entity text, record_id bigint) returns jsonb
language plpgsql stable security definer set search_path=pg_catalog,public,studio_private as $$
declare result jsonb;
begin
 execute format('select to_jsonb(t) from public.%I t where id=$1',entity) into result using record_id;
 if result is null then return null; end if;
 if entity='halls' then
  result:=result||jsonb_build_object('equipmentIds',coalesce((select jsonb_agg(id) from public.equipment where "hallId"=record_id),'[]'),
    'bookingIds',coalesce((select jsonb_agg(id) from public.bookings where "hallId"=record_id),'[]'));
 elsif entity='clients' then
  result:=result||jsonb_build_object('card',(select jsonb_build_object('id',id,'number',number,'issuedAt',"issuedAt",'expiresAt',"expiresAt",'discountPercent',"discountPercent") from public.subscriptions where "clientId"=record_id and "deletedAt" is null));
 elsif entity='photographers' then
  result:=result||jsonb_build_object('hallIds',coalesce((select jsonb_agg("hallId") from public.photographer_halls where "photographerId"=record_id),'[]'),
   'bookingIds',coalesce((select jsonb_agg("bookingId") from public.booking_photographers where "photographerId"=record_id),'[]'));
 elsif entity='bookings' then
  result:=result||jsonb_build_object('clientName',(select "fullName" from public.clients where id=(result->>'clientId')::bigint),
   'hall',(select jsonb_build_object('id',id,'name',name) from public.halls where id=(result->>'hallId')::bigint),
   'photographerIds',coalesce((select jsonb_agg("photographerId") from public.booking_photographers where "bookingId"=record_id),'[]'),
   'serviceIds',coalesce((select jsonb_agg("serviceId") from public.booking_services where "bookingId"=record_id),'[]'));
 end if;
 return result;
end $$;

create function studio_private.check_booking(booking_id bigint, reprice boolean default true) returns void
language plpgsql security definer set search_path=pg_catalog,public,studio_private as $$
declare b public.bookings; h public.halls; discount integer:=0; hall_cost numeric; people_cost numeric; service_cost numeric; total numeric;
begin
 select * into b from public.bookings where id=booking_id;
 select * into h from public.halls where id=b."hallId" and "deletedAt" is null;
 if h.id is null then perform studio_private.fail('hallId','Выберите активный зал'); end if;
 if not exists(select 1 from public.clients where id=b."clientId" and "deletedAt" is null) then perform studio_private.fail('clientId','Выберите активного клиента'); end if;
 if b.participants>h.capacity then perform studio_private.fail('participants','Количество участников превышает вместимость зала'); end if;
 if not exists(select 1 from public.booking_photographers where "bookingId"=b.id) then perform studio_private.fail('photographerIds','Выберите хотя бы одного фотографа'); end if;
 if exists(select 1 from public.booking_photographers bp left join public.photographers p on p.id=bp."photographerId"
  where bp."bookingId"=b.id and (p."deletedAt" is not null or not exists(select 1 from public.photographer_halls ph where ph."photographerId"=p.id and ph."hallId"=h.id))) then
  perform studio_private.fail('photographerIds','Фотограф не работает в выбранном зале'); end if;
 if exists(select 1 from public.booking_services bs join public.services s on s.id=bs."serviceId" where bs."bookingId"=b.id and s."deletedAt" is not null) then perform studio_private.fail('serviceIds','Выберите активные услуги'); end if;
 if b.status='active' and b."deletedAt" is null and exists(
  select 1 from public.bookings other where other.id<>b.id and other.status='active' and other."deletedAt" is null
   and tsrange(other.date+other."startTime",other.date+other."startTime"+make_interval(hours=>other."durationHours"),'[)')
       && tsrange(b.date+b."startTime",b.date+b."startTime"+make_interval(hours=>b."durationHours"),'[)')
   and (other."hallId"=b."hallId" or exists(select 1 from public.booking_photographers a join public.booking_photographers c on a."photographerId"=c."photographerId" where a."bookingId"=b.id and c."bookingId"=other.id))
 ) then raise sqlstate 'PT409' using message='Зал или фотограф занят в выбранное время'; end if;
 if reprice then
  select "discountPercent" into discount from public.subscriptions where "clientId"=b."clientId" and "deletedAt" is null and b.date between "issuedAt" and "expiresAt";
  discount:=coalesce(discount,0); hall_cost:=h."hourlyRate"*b."durationHours";
  select coalesce(sum(p."hourlyRate"),0)*b."durationHours" into people_cost from public.photographers p join public.booking_photographers bp on bp."photographerId"=p.id where bp."bookingId"=b.id;
  select coalesce(sum(s.price),0) into service_cost from public.services s join public.booking_services bs on bs."serviceId"=s.id where bs."bookingId"=b.id;
  total:=round(hall_cost*(100-discount)/100+people_cost+service_cost,2);
  if (select coalesce(sum(amount),0) from public.payments where "bookingId"=b.id and status='paid' and "deletedAt" is null)>total then raise sqlstate 'PT409' using message='Стоимость меньше уже внесённой оплаты'; end if;
  update public.bookings set "totalPrice"=total,"costBreakdown"=jsonb_build_object('hall',hall_cost,'photographers',people_cost,'services',service_cost,'discountPercent',discount,'discount',round(hall_cost*discount/100,2),'total',total) where id=b.id;
 end if;
end $$;

-- All mutations go through this RPC, so permissions, validation and conflicts
-- cannot be bypassed by writing directly to a REST table.
create function studio_private.save_record(entity text, record_id bigint, payload jsonb) returns jsonb
language plpgsql security definer set search_path=pg_catalog,public,studio_private as $$
declare data jsonb; old_data jsonb; key text; columns_sql text; values_sql text; result_id bigint; related bigint; profile public.profiles;
begin
 profile:=studio_private.current_profile();
 perform pg_advisory_xact_lock(7940401);
 if record_id is not null then
  old_data:=studio_private.row_json(entity,record_id);
  if old_data is null then raise sqlstate 'PT404' using message='Запись не найдена'; end if;
 end if;
 data:=coalesce(old_data,'{}')||payload;
 if entity='bookings' then
  data:=jsonb_build_object('status','active','startTime','10:00','comment','')||data;
  if record_id is null then
   if coalesce(data->>'accessCode','')='' then data:=data||jsonb_build_object('accessCode','FF-'||upper(substr(md5(random()::text),1,12))); end if;
   if profile.role='client' then
    if coalesce((data->>'clientId')::bigint,profile."clientId")<>profile."clientId" then raise sqlstate 'PT403' using message='Можно бронировать только для себя'; end if;
    data:=data||jsonb_build_object('clientId',profile."clientId",'status','active','accessCode','FF-'||upper(substr(md5(random()::text),1,12)));
   end if;
  end if;
  if record_id is null or data->>'date'<>old_data->>'date' or data->>'startTime'<>old_data->>'startTime' then
   if (data->>'date')::date+(data->>'startTime')::time<(now() at time zone 'Europe/Moscow') then perform studio_private.fail('date','Выберите будущее время съёмки'); end if;
  end if;
 end if;
 perform studio_private.validate(entity,data);
 -- Only real editable table columns are accepted. Derived fields and identities
 -- are never copied from the client.
 select string_agg(format('%I',a.attname),',' order by a.attnum),
        string_agg(format('(jsonb_populate_record(null::public.%I,$1)).%I',entity,a.attname),',' order by a.attnum)
 into columns_sql,values_sql
 from pg_attribute a where a.attrelid=format('public.%I',entity)::regclass and a.attnum>0 and not a.attisdropped
  and a.attname not in ('id','deletedAt','totalPrice','costBreakdown') and data ? a.attname;
 if record_id is null then
  execute format('insert into public.%I(%s) select %s returning id',entity,columns_sql,values_sql) into result_id using data;
 else
  execute format('update public.%I set (%s)=(select %s) where id=$2 returning id',entity,columns_sql,values_sql) into result_id using data,record_id;
 end if;
 if entity='photographers' then
  delete from public.photographer_halls where "photographerId"=result_id;
  for related in select distinct value::bigint from jsonb_array_elements_text(coalesce(data->'hallIds','[]')) loop
   if not exists(select 1 from public.halls where id=related and "deletedAt" is null) then perform studio_private.fail('hallIds','Выберите активные залы'); end if;
   insert into public.photographer_halls values(result_id,related);
  end loop;
  if not exists(select 1 from public.photographer_halls where "photographerId"=result_id) then perform studio_private.fail('hallIds','Выберите хотя бы один зал'); end if;
  if exists(select 1 from public.booking_photographers bp join public.bookings b on b.id=bp."bookingId" where bp."photographerId"=result_id and b.status='active' and b."deletedAt" is null and not exists(select 1 from public.photographer_halls ph where ph."photographerId"=result_id and ph."hallId"=b."hallId")) then raise sqlstate 'PT409' using message='В этом зале есть действующие съёмки фотографа'; end if;
 elsif entity='bookings' then
  delete from public.booking_photographers where "bookingId"=result_id;
  for related in select distinct value::bigint from jsonb_array_elements_text(coalesce(data->'photographerIds','[]')) loop insert into public.booking_photographers values(result_id,related); end loop;
  delete from public.booking_services where "bookingId"=result_id;
  for related in select distinct value::bigint from jsonb_array_elements_text(coalesce(data->'serviceIds','[]')) loop insert into public.booking_services values(result_id,related); end loop;
  perform studio_private.check_booking(result_id);
 elsif entity='equipment' then
  if not exists(select 1 from public.halls where id=(data->>'hallId')::bigint and "deletedAt" is null) then perform studio_private.fail('hallId','Выберите активный зал'); end if;
 elsif entity='subscriptions' then
  if not exists(select 1 from public.clients where id=(data->>'clientId')::bigint and "deletedAt" is null) then perform studio_private.fail('clientId','Выберите активного клиента'); end if;
 elsif entity='payments' then
  if not exists(select 1 from public.bookings where id=(data->>'bookingId')::bigint and "deletedAt" is null and status<>'cancelled') then perform studio_private.fail('bookingId','Выберите действующее бронирование'); end if;
  if (select coalesce(sum(amount),0) from public.payments where "bookingId"=(data->>'bookingId')::bigint and status='paid' and "deletedAt" is null)>(select "totalPrice" from public.bookings where id=(data->>'bookingId')::bigint) then raise sqlstate 'PT409' using message='Оплата превышает стоимость бронирования'; end if;
 end if;
 -- Preserve the original client form while keeping subscriptions normalized.
 if entity='clients' and payload ? 'cardNumber' and coalesce(payload->>'cardNumber','')<>'' then
  perform studio_private.save_record('subscriptions',(select id from public.subscriptions where "clientId"=result_id),
   jsonb_build_object('clientId',result_id,'number',payload->>'cardNumber','issuedAt',payload->>'cardIssuedAt','expiresAt',coalesce(nullif(payload->>'cardExpiresAt',''),((payload->>'cardIssuedAt')::date+365)::text),'discountPercent',coalesce((select "discountPercent" from public.subscriptions where "clientId"=result_id),0)));
 end if;
 return studio_private.row_json(entity,result_id);
exception
 when unique_violation then raise sqlstate 'PT409' using message='Такая запись или уникальный код уже существует';
 when foreign_key_violation then raise sqlstate 'PT409' using message='Связанная запись отсутствует или используется';
 when invalid_text_representation or datetime_field_overflow or invalid_datetime_format or numeric_value_out_of_range then
  perform studio_private.fail('date','Проверьте формат даты, времени и числовых значений'); return null;
end $$;

create function studio_private.delete_record(entity text, record_id bigint, hard boolean default false) returns void
language plpgsql security definer set search_path=pg_catalog,public,studio_private as $$
declare blocked boolean:=false;
begin
 perform pg_advisory_xact_lock(7940401);
 if entity='halls' then select exists(select 1 from public.bookings where "hallId"=record_id and (hard or "deletedAt" is null)) or exists(select 1 from public.equipment where "hallId"=record_id and (hard or "deletedAt" is null)) or exists(select 1 from public.photographer_halls where "hallId"=record_id) into blocked;
 elsif entity='clients' then select exists(select 1 from public.bookings where "clientId"=record_id and (hard or "deletedAt" is null)) or exists(select 1 from public.subscriptions where "clientId"=record_id and (hard or "deletedAt" is null)) or exists(select 1 from public.profiles where "clientId"=record_id) into blocked;
 elsif entity='photographers' then select exists(select 1 from public.booking_photographers bp join public.bookings b on b.id=bp."bookingId" where bp."photographerId"=record_id and (hard or b."deletedAt" is null)) into blocked;
 elsif entity='services' then select exists(select 1 from public.booking_services bs join public.bookings b on b.id=bs."bookingId" where bs."serviceId"=record_id and (hard or b."deletedAt" is null)) into blocked;
 elsif entity='bookings' then select exists(select 1 from public.payments where "bookingId"=record_id and (hard or "deletedAt" is null)) into blocked;
 end if;
 if blocked then raise sqlstate 'PT409' using message='Удаление невозможно: есть связанные записи'; end if;
 if hard then execute format('delete from public.%I where id=$1',entity) using record_id;
 else execute format('update public.%I set "deletedAt"=now() where id=$1',entity) using record_id;
 end if;
exception when foreign_key_violation then raise sqlstate 'PT409' using message='Запись используется в связанных данных';
end $$;

create function public.studio_api(endpoint text, method text default 'GET', query jsonb default '{}', payload jsonb default '{}') returns jsonb
language plpgsql security definer set search_path=pg_catalog,public,studio_private as $$
declare profile public.profiles; entity text; parts text[]; record_id bigint; action text;
 result jsonb; row_data jsonb; items jsonb:='[]'; total integer:=0; page_n integer; size_n integer; sort_field text; sort_expression text; descending boolean;
 candidate record; key text; value text; field text; conditions text:='true'; permission boolean; related bigint;
begin
